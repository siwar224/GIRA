/**
 * A layer drawn on the plate. Position and size are % of the plate image (1448×1086).
 * `clip` + `shift` show a single piece out of a cut-out that holds several (CSS clip-path,
 * the source file is untouched); `shift` re-centres the visible piece, in % of the cut-out.
 */
export type Layer = {
  src: string;
  x: number;
  y: number;
  w: number;
  rotate?: number;
  z?: number;
  clip?: string;
  shift?: [number, number];
  opacity?: number;
  /** Natural size of the image (default 600×600 cut-outs). */
  size?: [number, number];
  /** A full-plate overlay (e.g. the cheese dusting): fades in instead of dropping in. */
  overlay?: boolean;
  /** Mirror horizontally (so repeated pieces don't look like clones). */
  flip?: boolean;
};

